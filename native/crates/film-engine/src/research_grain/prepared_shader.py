"""Derive exact prepared samplers from the unchanged generic implementations.
Only RNG-free setup is moved. Rejection-loop source is copied, not rewritten.
"""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent
MARKER = '// Prepared distribution setup: generated by prepared_shader.py.\n'

def function(source, name):
    start = source.index('fn '+name+'(')
    opening = source.index('{', start)
    depth = 1
    end = opening+1
    while depth:
        depth += (source[end]=='{')-(source[end]=='}')
        end += 1
    return source[start:end]

def shader_extension(source):
    generic = function(source, 'sr_poisson')
    setup_start = generic.index(' let slam=')
    setup_end = generic.index('\n loop{', setup_start)
    setup = generic[setup_start:setup_end]
    small = 'let enlam=sf_exp_nonpositive(sf_neg(lam));'
    assert generic.count(small)==1
    names = ['enlam','loglam','b','a','invalpha','vr']
    fields = ','.join(n+':vec2<u32>' for n in names)
    out = MARKER+'struct SrPoissonSetup {'+fields+',}\n'
    out += '''fn sr_prepare_poisson(lam:vec2<u32>)->SrPoissonSetup{
 var result:SrPoissonSetup;
 if(sf_zero(lam)){return result;}
 if(sf_cmp(lam,vec2<u32>(0x00000000u,0x40240000u))<0){result.enlam=sf_exp_nonpositive(sf_neg(lam));return result;}
'''+setup+'\n return SrPoissonSetup(vec2<u32>(0u),loglam,b,a,invalpha,vr);\n}\n'
    prepared = generic.replace('fn sr_poisson(r:ptr<function,SoftRng>,lam:vec2<u32>)','fn sr_poisson_prepared(r:ptr<function,SoftRng>,lam:vec2<u32>,prepared:SrPoissonSetup)')
    prepared = prepared.replace(small,'let enlam=prepared.enlam;')
    prepared = prepared.replace(setup,' '+''.join('let '+n+'=prepared.'+n+';' for n in names[1:]))
    # Independent source proof that both rejection bodies retain exact spelling.
    assert prepared[prepared.index('\n loop{', prepared.index('let loglam=')):] == generic[setup_end:]
    return out+prepared+'\n'+shader_binomial(source)

def rust_source(source):
    ptrs = function(source, 'rk_poisson_ptrs')
    start = ptrs.index('    let slam =')
    end = ptrs.index('    loop {', start)
    setup = ptrs[start:end]
    mult = function(source, 'rk_poisson_mult')
    names=['enlam','loglam','b','a','invalpha','vr']
    out='// Generated by prepared_shader.py from guarded_sampler.rs; do not hand-edit.\nuse super::*;\n'
    out+='#[derive(Clone,Copy,Debug)] pub struct PoissonSetup {'+','.join('pub '+n+':f64' for n in names)+'}\n'
    out+='''pub fn prepare_poisson(lam:f64)->PoissonSetup{
 let mut out=PoissonSetup{enlam:0.,loglam:0.,b:0.,a:0.,invalpha:0.,vr:0.};
 if lam==0. {return out;}
 if lam<10. {out.enlam=exp_nonpositive(-lam);return out;}
'''+setup+'PoissonSetup{enlam:0.,loglam,b,a,invalpha,vr}\n}\n'
    out+='''pub fn poisson(rng:&mut Stream,lam:f64,prepared:PoissonSetup)->u64{
 if lam>=10. {poisson_ptrs(rng,lam,prepared)}else if lam==0. {0}else{poisson_mult(rng,lam,prepared)}
}\n'''
    ptrs=ptrs.replace('fn rk_poisson_ptrs(rng: &mut Stream, lam: f64)','fn poisson_ptrs(rng: &mut Stream, lam: f64, prepared:PoissonSetup)').replace(setup,'    '+''.join('let '+n+'=prepared.'+n+';' for n in names[1:])+'\n')
    mult=mult.replace('fn rk_poisson_mult(rng: &mut Stream, lam: f64)','fn poisson_mult(rng: &mut Stream, _lam: f64, prepared:PoissonSetup)').replace('let enlam = exp_nonpositive(-lam);','let enlam = prepared.enlam;')
    return out+ptrs+'\n'+mult+'\n'+rust_binomial(source)


def shader_binomial(source):
    out='struct SrBinomialSetup {v:array<vec2<u32>,18>,}\n'
    specs=[('sr_inversion',' var x=', ['q','nf','qn','error','bound']),('sr_btpe','var y=0i;', ['r','q','nf','fm','m','mf','p1','xm','xl','xr','c','laml','lamr','p2','p3','p4','nrq'])]
    for name,marker,names in specs:
        generic=function(source,name);start=generic.index('{')+1;end=generic.index(marker,start);setup=generic[start:end]
        guard='if(!sf_valid(qn)){(*r).failure=1u;return 0u;}'
        prep_setup=setup.replace(guard,'if(!sf_valid(qn)){sf_failed=1u;return out;}')
        out+='fn '+name.replace('sr_','sr_prepare_')+'(n:u32,pb:vec2<u32>)->SrBinomialSetup{\n var out:SrBinomialSetup;'+prep_setup
        for i,n in enumerate(names):
            value='sf_signed(m)' if n=='m' else 'sf_integer(bound)' if n=='bound' else n
            out+=f'out.v[{i}u]={value};'
        out+='return out;\n}\n'
        loads=''
        for i,n in enumerate(names):
            value=f'prepared.v[{i}u]'
            if n=='m':value=f'sf_floor({value})'
            if n=='bound':value=f'u32(sf_floor({value}))'
            loads+=f'let {n}={value};'
        if name=='sr_inversion':loads+=guard
        signature=generic[:start].replace(name+'(',name+'_prepared(').replace(')->u32{',',prepared:SrBinomialSetup)->u32{')
        candidate=signature+loads+generic[end:]
        assert candidate[candidate.index(marker):]==generic[end:]
        out+=candidate+'\n'
    wrapper=function(source,'sr_binomial')
    out+=wrapper.replace('fn sr_binomial(', 'fn sr_binomial_prepared(').replace(')->u32{',',prepared:SrBinomialSetup)->u32{').replace('sr_inversion(rng,n,pb)','sr_inversion_prepared(rng,n,pb,prepared)').replace('sr_inversion(rng,n,q)','sr_inversion_prepared(rng,n,q,prepared)').replace('sr_btpe(rng,n,pb)','sr_btpe_prepared(rng,n,pb,prepared)').replace('sr_btpe(rng,n,q)','sr_btpe_prepared(rng,n,q,prepared)')+'\n'
    prepare=wrapper.replace('fn sr_binomial(rng:ptr<function,SoftRng>,','fn sr_prepare_binomial(').replace(')->u32{',')->SrBinomialSetup{').replace('return n-','return ').replace('sr_inversion(rng,','sr_prepare_inversion(').replace('sr_btpe(rng,','sr_prepare_btpe(')
    out+=prepare+'\n'
    return out

def rust_binomial(source):
    out='#[derive(Clone,Copy,Debug)] pub struct BinomialSetup {pub values:[f64;18]}\n'
    specs=[('rk_binomial_inversion','    let mut x:', ['q','qn','inversion_error','bound']),('rk_binomial_btpe','    let y: i64;', ['r','q','nf','fm','m','p1','xm','xl','xr','c','laml','lamr','p2','p3','p4','nrq'])]
    for name,marker,names in specs:
        generic=function(source,name);start=generic.index('{')+1;end=generic.index(marker,start);setup=generic[start:end]
        guard='if !qn.is_finite() {rng.failure=Some(Failure::Domain);return 0;}'
        prep_setup=setup.replace(guard,'if !qn.is_finite() {out.values[1]=qn;return out;}')
        out+='fn '+name.replace('rk_binomial_','prepare_')+'(n:u64,p:f64)->BinomialSetup{\n let mut out=BinomialSetup{values:[0.;18]};'+prep_setup
        for i,n in enumerate(names):out+=f'out.values[{i}]={n}'+(' as f64' if n in ['m','bound'] else '')+';'
        out+='out\n}\n'
        loads=''
        for i,n in enumerate(names):loads+=f'let {n}=prepared.values[{i}]'+(' as i64' if n=='m' else ' as u64' if n=='bound' else '')+';'
        if name=='rk_binomial_inversion':loads+=guard
        candidate=generic[:start].replace(name+'(',name.replace('rk_binomial_','prepared_')+'(').replace(') -> u64 {',', prepared:BinomialSetup) -> u64 {')+loads+'\n'+generic[end:]
        assert candidate[candidate.index(marker):]==generic[end:]
        out+=candidate+'\n'
    wrapper=function(source,'rk_binomial')
    out+='pub '+wrapper.replace('fn rk_binomial(', 'fn binomial(').replace(') -> u64 {',',prepared:BinomialSetup) -> u64 {').replace('rk_binomial_inversion(rng, n, p)','prepared_inversion(rng, n, p, prepared)').replace('rk_binomial_inversion(rng, n, q)','prepared_inversion(rng, n, q, prepared)').replace('rk_binomial_btpe(rng, n, p)','prepared_btpe(rng, n, p, prepared)').replace('rk_binomial_btpe(rng, n, q)','prepared_btpe(rng, n, q, prepared)')+'\n'
    prep=wrapper.replace('fn rk_binomial(rng: &mut Stream,','fn prepare_binomial(').replace(') -> u64 {',') -> BinomialSetup {').replace('n - rk_binomial_', 'rk_binomial_').replace('rk_binomial_inversion(rng,','prepare_inversion(').replace('rk_binomial_btpe(rng,','prepare_btpe(')
    out+='pub '+prep+'\n'
    return out

def shader_runtime(generic):
    # Generic reference lives only offline; production shares one rejection body.
    runtime=generic
    replacements={
        'sr_poisson':'fn sr_poisson(r:ptr<function,SoftRng>,lam:vec2<u32>)->u32{return sr_poisson_prepared(r,lam,sr_prepare_poisson(lam));}',
        'sr_binomial':'fn sr_binomial(r:ptr<function,SoftRng>,n:u32,pb:vec2<u32>)->u32{return sr_binomial_prepared(r,n,pb,sr_prepare_binomial(n,pb));}',
        'sr_inversion':'', 'sr_btpe':''}
    for name,wrapper in replacements.items():runtime=runtime.replace(function(generic,name),wrapper)
    return runtime+shader_extension(generic)

