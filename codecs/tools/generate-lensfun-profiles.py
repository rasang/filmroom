#!/usr/bin/env python3
"""Generate the opted-in optical constants from the pinned Lensfun subset.

This is a build-maintenance tool, never an Android runtime XML parser. Adding a
profile here does not opt a camera into correction: the source identity and
reference-rectangle gates in lensfun.rs must also be qualified with real RAWs.
"""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lensfun' / 'approved.xml'
DEST = ROOT / 'src' / 'lensfun_profiles.rs'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = ET.parse(SOURCE).getroot()
    cameras = [c for c in root.findall('camera')
               if c.findtext('maker') == 'Canon' and c.findtext('model') == 'Canon EOS R']
    lenses = [l for l in root.findall('lens')
              if l.findtext('maker') == 'Canon' and l.findtext('model') == 'Canon RF 16mm F2.8 STM']
    if len(cameras) != 1 or len(lenses) != 1:
        raise ValueError('Missing or ambiguous approved camera/lens')
    camera, lens = cameras[0], lenses[0]
    rows = lens.findall('calibration/distortion')
    if len(rows) != 1 or rows[0].attrib.get('model') != 'ptlens':
        raise ValueError('RF16 qualification requires its single PTLens calibration')
    row = rows[0].attrib
    values = {name: float(row[name]) for name in ['focal', 'a', 'b', 'c']}
    if values['focal'] != 16.0:
        raise ValueError('Unexpected RF16 focal length')
    crop = float(lens.findtext('cropfactor'))
    camera_crop = float(camera.findtext('cropfactor'))
    # Explicit defaults from Lensfun's schema: centred, 3:2 calibration image.
    if lens.find('center') is not None or lens.find('aspect-ratio') is not None:
        raise ValueError('Review changed reference geometry before regenerating')
    tca_rows = lens.findall('calibration/tca')
    if len(tca_rows) != 1 or tca_rows[0].get('model') != 'poly3' or float(tca_rows[0].get('focal')) != 16.0:
        raise ValueError('RF16 qualification requires one poly3 TCA calibration')
    tca = tca_rows[0]
    tca_terms = [float(tca.get(k, '1' if k in ('vr', 'vb') else '0')) for k in ('vr', 'vb', 'cr', 'cb', 'br', 'bb')]
    vignette_rows = lens.findall('calibration/vignetting')
    vignette = []
    for node in vignette_rows:
        if node.get('model') != 'pa' or float(node.get('focal')) != 16.0:
            raise ValueError('RF16 qualification requires exact-focal PA vignetting')
        vignette.append({k: float(node.get(k)) for k in ('focal', 'aperture', 'distance', 'k1', 'k2', 'k3')})
    if len(vignette) != 10 or len({(r['aperture'], r['distance']) for r in vignette}) != 10:
        raise ValueError('Review changed RF16 vignetting calibration coverage')
    vignette_text = '\n'.join('    VignetteCalibration { focal_mm: %r, aperture: %r, distance_m: %r, terms: [%r, %r, %r] },' %
        tuple(r[k] for k in ('focal', 'aperture', 'distance', 'k1', 'k2', 'k3')) for r in vignette)
    text = f'''// Generated by tools/generate-lensfun-profiles.py from lensfun/approved.xml.
// Lensfun database contributors, CC BY-SA 3.0; see lensfun/PROVENANCE.json.
// Do not edit coefficients by hand. Runtime admission remains per operation.
use crate::lensfun_geometry::{{Calibration, CalibrationPoint, DistortionModel}};
use super::optics::{{TcaCalibration, VignetteCalibration}};

pub(super) const RF16_CAMERA_CROP: f64 = {camera_crop!r};
pub(super) const RF16_POINTS: [CalibrationPoint; 1] = [CalibrationPoint {{
    focal_mm: {values['focal']!r},
    model: DistortionModel::PtLens {{ a: {values['a']!r}, b: {values['b']!r}, c: {values['c']!r} }},
}}];
pub(super) const RF16_CALIBRATION: Calibration<'static> = Calibration {{
    crop_factor: {crop!r},
    aspect_ratio: 1.5,
    center: [0.0, 0.0],
    points: &RF16_POINTS,
}};
pub(super) const RF16_TCA: TcaCalibration = TcaCalibration {{
    focal_mm: 16.0,
    terms: {tca_terms!r},
}};
pub(super) const RF16_VIGNETTING: [VignetteCalibration; {len(vignette)}] = [
{vignette_text}
];
'''
    if args.check:
        if not DEST.is_file() or DEST.read_text() != text:
            raise SystemExit('Lensfun generated constants are stale')
        print('Lensfun constants match the pinned XML')
    else:
        DEST.write_text(text)
        print(DEST)


if __name__ == '__main__':
    main()
