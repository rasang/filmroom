#!/usr/bin/env python3
"""Compile the complete pinned Lensfun schema-2 database into offline tables.

This maintenance tool uses only the Python standard library. Android receives
static records and sorted name indexes, never an XML parser or a Lensfun shared
library. Original XML is retained byte-for-byte for provenance. Duplicate
calibration keys follow Lensfun 0.3.4's last-value-wins loader semantics.
"""
import argparse
import collections
import hashlib
import json
import math
from pathlib import Path
import re
import struct
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lensfun' / 'approved.xml'
DEST = ROOT / 'src' / 'lensfun_profiles.rs'
DATABASE = ROOT / 'lensfun' / 'database'
PROVENANCE = ROOT / 'lensfun' / 'PROVENANCE.json'
STATS = ROOT / 'lensfun' / 'DATABASE-STATS.json'


def legacy_constants():
    root = ET.parse(SOURCE).getroot()
    cameras = [c for c in root.findall('camera')
               if c.findtext('maker') == 'Canon' and c.findtext('model') == 'Canon EOS R']
    lenses = [l for l in root.findall('lens')
              if l.findtext('maker') == 'Canon' and l.findtext('model') == 'Canon RF 16mm F2.8 STM']
    if len(cameras) != 1 or len(lenses) != 1:
        raise ValueError('Missing or ambiguous approved camera/lens')
    camera, lens = cameras[0], lenses[0]
    rows = lens.findall('calibration/distortion')
    if len(rows) != 1 or rows[0].attrib.get('model') != 'ptlens':
        raise ValueError('RF16 qualification requires its single PTLens calibration')
    row = rows[0].attrib
    values = {name: float(row[name]) for name in ['focal', 'a', 'b', 'c']}
    if values['focal'] != 16.0:
        raise ValueError('Unexpected RF16 focal length')
    crop = float(lens.findtext('cropfactor'))
    camera_crop = float(camera.findtext('cropfactor'))
    # Explicit defaults from Lensfun's schema: centred, 3:2 calibration image.
    if lens.find('center') is not None or lens.find('aspect-ratio') is not None:
        raise ValueError('Review changed reference geometry before regenerating')
    tca_rows = lens.findall('calibration/tca')
    if len(tca_rows) != 1 or tca_rows[0].get('model') != 'poly3' or float(tca_rows[0].get('focal')) != 16.0:
        raise ValueError('RF16 qualification requires one poly3 TCA calibration')
    tca = tca_rows[0]
    tca_terms = [float(tca.get(k, '1' if k in ('vr', 'vb') else '0')) for k in ('vr', 'vb', 'cr', 'cb', 'br', 'bb')]
    vignette_rows = lens.findall('calibration/vignetting')
    vignette = []
    for node in vignette_rows:
        if node.get('model') != 'pa' or float(node.get('focal')) != 16.0:
            raise ValueError('RF16 qualification requires exact-focal PA vignetting')
        vignette.append({k: float(node.get(k)) for k in ('focal', 'aperture', 'distance', 'k1', 'k2', 'k3')})
    if len(vignette) != 10 or len({(r['aperture'], r['distance']) for r in vignette}) != 10:
        raise ValueError('Review changed RF16 vignetting calibration coverage')
    vignette_text = '\n'.join('    VignetteCalibration { focal_mm: %r, aperture: %r, distance_m: %r, terms: [%r, %r, %r] },' %
        tuple(r[k] for k in ('focal', 'aperture', 'distance', 'k1', 'k2', 'k3')) for r in vignette)
    return f'''// Generated by tools/generate-lensfun-profiles.py from the pinned full database.
// Lensfun database contributors, CC BY-SA 3.0; see lensfun/PROVENANCE.json.
// Do not edit coefficients by hand. Runtime admission remains per operation.
use crate::lensfun_geometry::{{Calibration, CalibrationPoint, DistortionModel}};
use super::optics::{{TcaCalibration, VignetteCalibration}};
use super::database::{{CameraProfile, LensProfile, MountProfile, NameIndex, Projection}};

// Retained as independent compatibility fixtures for the previously qualified route.
pub(super) const RF16_CAMERA_CROP: f64 = {camera_crop!r};
pub(super) const RF16_POINTS: [CalibrationPoint; 1] = [CalibrationPoint {{
    focal_mm: {values['focal']!r},
    model: DistortionModel::PtLens {{ a: {values['a']!r}, b: {values['b']!r}, c: {values['c']!r} }},
}}];
pub(super) const RF16_CALIBRATION: Calibration<'static> = Calibration {{
    crop_factor: {crop!r},
    aspect_ratio: 1.5,
    center: [0.0, 0.0],
    points: &RF16_POINTS,
}};
pub(super) const RF16_TCA: TcaCalibration = TcaCalibration {{
    focal_mm: 16.0,
    terms: {tca_terms!r},
}};
pub(super) const RF16_VIGNETTING: [VignetteCalibration; {len(vignette)}] = [
{vignette_text}
];
'''


def f32(value):
    return struct.unpack('<f', struct.pack('<f', float(value)))[0]


def number(value):
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f'Nonfinite calibration number: {value!r}')
    return result


def rust_number(value):
    return repr(number(value))


def quoted(value):
    if any(ord(c) < 32 for c in value):
        raise ValueError(f'Control character in database text: {value!r}')
    return json.dumps(value, ensure_ascii=False)


def strings(values):
    return '&[' + ', '.join(quoted(v) for v in values) + ']'


def aliases(node, tag):
    values = [(n.text or '').strip() for n in node.findall(tag)]
    if not values or any(not v for v in values):
        raise ValueError(f'Missing {tag} in {node.tag}')
    return list(dict.fromkeys(values))


def name_key(value):
    result = ''
    for ch in value.lower():
        if ch.isspace():
            continue
        if ch in '\u2010\u2011\u2012\u2013\u2212':
            ch = '-'
        if ch == '/' and result.endswith('f'):
            continue
        result += ch
    return result


def maker_key(value):
    value = ''.join(c for c in value.lower() if c.isalnum())
    return {
        'nikoncorporation': 'nikon', 'canoninc': 'canon', 'sonycorporation': 'sony',
        'fujifilmcorporation': 'fujifilm', 'fujiphotofilmcoltd': 'fujifilm',
        'olympusimagingcorp': 'olympus', 'olympuscorporation': 'olympus',
        'olympusopticalcoltd': 'olympus', 'omdigitalsolutions': 'omsystem',
        'omdigitalsolutionscorporation': 'omsystem', 'ricohimagingcompanyltd': 'ricoh',
        'ricohimagingcompany': 'ricoh', 'ricohcoltd': 'ricoh', 'leicacameraag': 'leica',
        'lumix': 'panasonic', 'panasoniccorporation': 'panasonic', 'panasonicentertainmentcommunicationcoltd': 'panasonic',
        'carlzeiss': 'zeiss',
    }.get(value, value)


def name_variants(names, makers):
    prefixes = {name_key(m) for m in makers} | {maker_key(m) for m in makers}
    result = set()
    expanded = list(names)
    for name in names:
        # A combined I/II profile explicitly calibrates both generations. Most
        # original first-generation EXIF names omit the Roman numeral. Preserve
        # the combined source name and add only the generations it declares.
        shared = re.fullmatch(r'(.*?)\s+(?:I/II|\(Vers\.\s*I/II\))', name, re.I)
        if shared:
            base = shared.group(1)
            expanded.extend((base, base + ' I', base + ' II'))
    for name in expanded:
        normalized = name_key(name)
        result.add(normalized)
        stripped = normalized
        for prefix in sorted(prefixes, key=len, reverse=True):
            if stripped.startswith(prefix) and len(stripped) > len(prefix):
                stripped = stripped[len(prefix):]
                break
        result.add(stripped)
        for prefix in prefixes:
            result.add(prefix + stripped)
    return result


def attribute_range(node, tag):
    field = node.find(tag)
    if field is None:
        return [0.0, 0.0]
    if field.get('value') is not None:
        value = f32(field.get('value'))
        return [value, value]
    return [f32(field.get('min', '0')), f32(field.get('max', '0'))]


# The three case-insensitive expressions and group meanings are from
# Lensfun 0.3.4 lens.cpp's _lf_parse_lens_name (LGPL-3.0-or-later).
LENS_NAME_PATTERNS = [
    (re.compile(r'(\s+|^)([0-9]+[0-9.]*)(-[0-9]+[0-9.]*)?(mm)?\s+(f/|f|1/|1:)?([0-9.]+)(-[0-9.]+)?', re.I), (2, 3, 6)),
    (re.compile(r'\s+1:([0-9.]+)(-[0-9.]+)?\s+([0-9.]+)(-[0-9.]+)?(mm)?', re.I), (3, 4, 1)),
    (re.compile(r'([0-9.]+)(-[0-9.]+)?\s*/\s*([0-9.]+)(-[0-9.]+)?', re.I), (3, 4, 1)),
]


def guessed_ranges(lens):
    focal = attribute_range(lens, 'focal')
    aperture = attribute_range(lens, 'aperture')
    minf, maxf, mina, maxa = math.inf, -math.inf, math.inf, -math.inf
    model = lens.findtext('model', '')
    if not aperture[0] or not focal[0]:
        if not any(word in model for word in ('adapter', 'reducer', 'booster', 'extender', 'converter')):
            for pattern, groups in LENS_NAME_PATTERNS:
                match = pattern.search(model)
                if match:
                    # Native atof accepts the numeric prefix of a name token;
                    # profile XML coefficients themselves remain strict numbers.
                    def name_number(token):
                        numeric = re.match(r'(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)', token.lstrip('-'))
                        return f32(numeric.group()) if numeric else 0.0
                    parsed = [name_number(match.group(g)) if match.group(g) else None for g in groups]
                    if parsed[0] is not None: minf = parsed[0]
                    if parsed[1] is not None: maxf = parsed[1]
                    if parsed[2] is not None: mina = parsed[2]
                    break
        for row in lens.findall('calibration/*'):
            value = f32(row.get('focal'))
            minf, maxf = min(minf, value), max(maxf, value)
            if row.tag == 'vignetting':
                value = f32(row.get('aperture'))
                mina, maxa = min(mina, value), max(maxa, value)
    for target, values in ((focal, (minf, maxf)), (aperture, (mina, maxa))):
        for i, value in enumerate(values):
            if not target[i] and math.isfinite(value): target[i] = value
    if not focal[1]: focal[1] = focal[0]
    if not focal[0] or focal[1] < focal[0]:
        raise ValueError(f'Unusable focal range for {model}: {focal}')
    return focal, aperture


def load_rows(lens, kind, stats):
    rows = {}
    for node in lens.findall(f'calibration/{kind}'):
        stats['original_samples'][kind] += 1
        keys = ('focal', 'aperture', 'distance') if kind == 'vignetting' else ('focal',)
        key = tuple(f32(node.get(k)) for k in keys)
        if key in rows: stats['replaced_duplicate_samples'][kind] += 1
        # Assignment preserves the first slot, matching _lf_addobj.
        rows[key] = dict(node.attrib)
    stats['compiled_samples'][kind] += len(rows)
    return list(rows.values())


def vector(values):
    return '[' + ', '.join(rust_number(v) for v in values) + ']'


def compile_database():
    provenance = json.loads(PROVENANCE.read_text())
    files = sorted(DATABASE.glob('*.xml'))
    observed = {p.name: {'sha256': hashlib.sha256(p.read_bytes()).hexdigest(), 'bytes': p.stat().st_size} for p in files}
    if observed != provenance['database_files']:
        raise ValueError('Pinned database differs from PROVENANCE.json')
    legacy = provenance['legacy_subset']
    if hashlib.sha256((ROOT / 'lensfun' / legacy['file']).read_bytes()).hexdigest() != legacy['sha256']:
        raise ValueError('Legacy compatibility fixture differs from PROVENANCE.json')
    lens_rows, camera_rows, mount_rows = [], [], []
    lens_index, camera_index = set(), set()
    stats = {'xml_files': len(files), 'xml_bytes': sum(v['bytes'] for v in observed.values()),
        'source_archive_sha256': provenance['source_archive_sha256'],
        'original_samples': collections.Counter(), 'compiled_samples': collections.Counter(),
        'replaced_duplicate_samples': collections.Counter(), 'records_with': collections.Counter(),
        'projection_records': collections.Counter(), 'maker_model_keys': set(), 'camera_variants': 0}
    projection_names = {'rectilinear': 'Rectilinear', 'fisheye': 'Fisheye', 'equisolid': 'Equisolid',
        'stereographic': 'Stereographic', 'panoramic': 'Panoramic'}
    parsed = [(p, ET.parse(p).getroot()) for p in files]
    public_mounts = {m.findtext('name') for _, root in parsed for m in root.findall('mount')}
    for path, root in parsed:
        if root.tag != 'lensdatabase' or root.get('version') != '2':
            raise ValueError(f'Unexpected database schema in {path.name}')
        for mount in root.findall('mount'):
            mount_rows.append('    MountProfile { name: %s, compatible: %s },' %
                (quoted(mount.findtext('name')), strings([n.text for n in mount.findall('compat')])))
        for i, camera in enumerate(root.findall('camera')):
            makers, models = aliases(camera, 'maker'), aliases(camera, 'model')
            variant = camera.findtext('variant', '')
            mount = camera.findtext('mount')
            crop = number(camera.findtext('cropfactor'))
            stats['camera_variants'] += bool(variant)
            names = models + ([variant] if variant else [])
            for mk in {maker_key(m) for m in makers}:
                for name in name_variants(names, makers): camera_index.add((f'{mk}|{name}', len(camera_rows)))
            fixed = (path.name.startswith('compact-') or path.name == 'actioncams.xml') and mount not in public_mounts
            camera_rows.append('    CameraProfile { id: %s, maker: %s, model: %s, maker_aliases: %s, model_aliases: %s, variant: %s, mount: %s, crop_factor: %s, fixed_lens: %s },' %
                (quoted(f'lf-camera-{path.stem}-{i}'), quoted(makers[0]), quoted(models[0]), strings(makers), strings(models), quoted(variant), quoted(mount), rust_number(crop), str(fixed).lower()))
        for i, lens in enumerate(root.findall('lens')):
            makers, models = aliases(lens, 'maker'), aliases(lens, 'model')
            mounts = aliases(lens, 'mount')
            crop = number(lens.findtext('cropfactor'))
            ratio = lens.findtext('aspect-ratio', '3:2')
            aspect = number(ratio) if ':' not in ratio else number(ratio.split(':')[0]) / number(ratio.split(':')[1])
            projection = lens.findtext('type', 'rectilinear')
            if projection not in projection_names: raise ValueError(f'Unknown projection: {projection}')
            stats['projection_records'][projection] += 1
            focal_range, aperture_range = guessed_ranges(lens)
            rows = {kind: load_rows(lens, kind, stats) for kind in ('distortion', 'tca', 'vignetting')}
            for kind, values in rows.items(): stats['records_with'][kind] += bool(values)
            stats['records_with']['all_three'] += all(rows.values())
            stats['records_with']['extras_without_distortion'] += not rows['distortion'] and bool(rows['tca'] or rows['vignetting'])
            stats['maker_model_keys'].add((makers[0], models[0]))
            distortion = []
            for row in rows['distortion']:
                kind = row['model']
                if kind == 'ptlens': model = 'DistortionModel::PtLens { a: %s, b: %s, c: %s }' % tuple(rust_number(row.get(k, '0')) for k in ('a', 'b', 'c'))
                elif kind == 'poly3': model = 'DistortionModel::Poly3 { k1: %s }' % rust_number(row.get('k1', '0'))
                elif kind == 'poly5': model = 'DistortionModel::Poly5 { k1: %s, k2: %s }' % tuple(rust_number(row.get(k, '0')) for k in ('k1', 'k2'))
                else: raise ValueError(f'Unknown distortion model: {kind}')
                distortion.append('CalibrationPoint { focal_mm: %s, model: %s }' % (rust_number(row['focal']), model))
            tca = []
            for row in rows['tca']:
                if row['model'] == 'linear': terms = [row.get('kr', '1'), row.get('kb', '1'), 0, 0, 0, 0]
                elif row['model'] == 'poly3': terms = [row.get(k, '1' if k in ('vr', 'vb') else '0') for k in ('vr', 'vb', 'cr', 'cb', 'br', 'bb')]
                else: raise ValueError(f'Unknown TCA model: {row["model"]}')
                tca.append('TcaCalibration { focal_mm: %s, terms: %s }' % (rust_number(row['focal']), vector(terms)))
            vignette = []
            for row in rows['vignetting']:
                if row['model'] != 'pa': raise ValueError(f'Unknown vignetting model: {row["model"]}')
                vignette.append('VignetteCalibration { focal_mm: %s, aperture: %s, distance_m: %s, terms: %s }' %
                    (rust_number(row['focal']), rust_number(row['aperture']), rust_number(row['distance']), vector(row[k] for k in ('k1', 'k2', 'k3'))))
            real_focal = [[row['focal'], row['real-focal']] for row in rows['distortion'] if 'real-focal' in row]
            variants = name_variants(models, makers)
            for name in variants: lens_index.add((name, len(lens_rows)))
            primary = name_key(models[0])
            for prefix in sorted({name_key(m) for m in makers} | {maker_key(m) for m in makers}, key=len, reverse=True):
                if primary.startswith(prefix) and len(primary) > len(prefix): primary = primary[len(prefix):]; break
            attachment = any(word in models[0].lower() for word in ('adapter', 'reducer', 'booster', 'extender', 'converter', 'magnifier', '+', 'with '))
            discrete = attachment and (path.name.startswith('compact-') or path.name == 'actioncams.xml') and any(name_key(m) == 'fixedlens' for m in models)
            stats['records_with']['discrete_fixed_lens_groups'] += discrete
            center_node = lens.find('center')
            center = [number(center_node.get(k, '0')) for k in ('x', 'y')] if center_node is not None else [0.0, 0.0]
            lens_rows.append('    LensProfile {\n' +
                '        id: %s, maker: %s, model: %s,\n' % (quoted(f'lf-{path.stem}-{i}'), quoted(makers[0]), quoted(models[0])) +
                '        maker_aliases: %s, model_aliases: %s, maker_key: %s, model_key: %s,\n' % (strings(makers), strings(models), quoted(maker_key(makers[0])), quoted(primary)) +
                '        mounts: %s, projection: Projection::%s,\n' % (strings(mounts), projection_names[projection]) +
                '        calibration: Calibration { crop_factor: %s, aspect_ratio: %s, center: %s, points: &[\n            %s\n        ] },\n' % (rust_number(crop), rust_number(aspect), vector(center), ',\n            '.join(distortion)) +
                '        tca: &[\n            %s\n        ],\n' % ',\n            '.join(tca) +
                '        vignetting: &[\n            %s\n        ],\n' % ',\n            '.join(vignette) +
                '        focal_range: %s, aperture_range: %s, real_focal: &[%s],\n' % (vector(focal_range), vector(aperture_range), ', '.join(vector(p) for p in real_focal)) +
                '        source_file: %s, requires_attachment_identity: %s, discrete_focals: %s,\n    },' % (quoted(path.name), str(attachment).lower(), str(discrete).lower()))
    stats['camera_records'] = len(camera_rows)
    stats['lens_records'] = len(lens_rows)
    stats['mount_records'] = len(mount_rows)
    stats['maker_model_names'] = len(stats.pop('maker_model_keys'))
    stats['camera_index_entries'] = len(camera_index)
    stats['lens_index_entries'] = len(lens_index)
    if (stats['xml_files'], stats['camera_records'], stats['lens_records'], stats['mount_records']) != (56, 1059, 1580, 52):
        raise ValueError('Unexpected pinned database inventory')
    code = legacy_constants()
    for name, kind, values in [('CAMERAS', 'CameraProfile', camera_rows), ('MOUNTS', 'MountProfile', mount_rows), ('LENSES', 'LensProfile', lens_rows)]:
        code += '\npub(super) static %s: &[%s] = &[\n%s\n];\n' % (name, kind, '\n'.join(values))
    for name, values in [('CAMERA_INDEX', camera_index), ('LENS_INDEX', lens_index)]:
        code += '\npub(super) static %s: &[NameIndex] = &[\n%s\n];\n' % (name, '\n'.join('    NameIndex { key: %s, record: %d },' % (quoted(key), record) for key, record in sorted(values)))
    # Empty calibration arrays must not leave indented blank lines in the source.
    code = '\n'.join(line.rstrip(' \t') for line in code.split('\n'))
    stats['generated_source_bytes'] = len(code.encode())
    return code, json.dumps(stats, ensure_ascii=False, sort_keys=True, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, stats = compile_database()
    if args.check:
        if not DEST.is_file() or DEST.read_text() != text:
            raise SystemExit('Lensfun generated constants are stale')
        if not STATS.is_file() or STATS.read_text() != stats:
            raise SystemExit('Lensfun database statistics are stale')
        print('Lensfun full database: 56 XML, 1059 cameras, 1580 lenses; tables/indexes match pinned inputs')
    else:
        DEST.write_text(text)
        STATS.write_text(stats)
        print(f'{DEST}: {len(text.encode()):,} bytes; full database compiled')


if __name__ == '__main__':
    main()
